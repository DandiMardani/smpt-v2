create function public.process_bundle_package_packing(
  p_date date,
  p_package_id bigint,
  p_location_id bigint,
  p_quantity numeric,
  p_notes text,
  p_components jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
  v_package_name text;
  v_packing_code text;
  v_packing_id bigint;
  v_event_id bigint;
  v_supplied_count integer;
  v_distinct_count integer;
  v_component jsonb;
  v_fg_id bigint;
  v_qty_per_bundle numeric;
  v_unit text;
  v_recipe record;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    if coalesce(auth.role(), '') <> 'authenticated' or auth.uid() is null then
      raise exception 'Sesi tidak valid atau belum terautentikasi.'
        using errcode = '42501';
    end if;

    if not coalesce(public.has_permission('bundling_isian.write'), false) then
      raise exception 'Tidak memiliki izin bundling_isian.write.'
        using errcode = '42501';
    end if;
  end if;

  if p_quantity is null or p_quantity <= 0
     or p_quantity::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Jumlah packing harus lebih besar dari nol.';
  end if;
  if p_package_id is null or p_package_id <= 0
     or p_location_id is null or p_location_id <= 0 then
    raise exception 'Paket atau lokasi tidak valid.';
  end if;
  if p_components is null or pg_catalog.jsonb_typeof(p_components) <> 'array'
     or pg_catalog.jsonb_array_length(p_components) = 0
     or pg_catalog.jsonb_array_length(p_components) > 100 then
    raise exception 'Komponen packing harus berupa array berisi 1 sampai 100 item.';
  end if;

  lock table public.bundle_package_recipes in share mode;

  select bp.name
    into v_package_name
  from public.bundle_packages bp
  where bp.id = p_package_id
    and bp.status = 'AKTIF'
  for share;

  if not found then
    raise exception 'Paket aktif tidak ditemukan.';
  end if;

  for v_component in
    select e.value
    from pg_catalog.jsonb_array_elements(p_components) as e(value)
  loop
    if pg_catalog.jsonb_typeof(v_component) <> 'object'
       or coalesce(v_component ->> 'finished_good_id', '') !~ '^[1-9][0-9]*$' then
      raise exception 'Data komponen packing tidak valid.';
    end if;

    v_fg_id := (v_component ->> 'finished_good_id')::bigint;
    v_qty_per_bundle := coalesce(
      nullif(v_component ->> 'qty_used', '')::numeric,
      nullif(v_component ->> 'qty', '')::numeric,
      nullif(v_component ->> 'qty_per_bundle', '')::numeric
    );

    if v_qty_per_bundle is null or v_qty_per_bundle <= 0
       or v_qty_per_bundle::text in ('NaN', 'Infinity', '-Infinity') then
      raise exception 'Kuantitas komponen harus lebih besar dari nol.';
    end if;
  end loop;

  select count(*), count(distinct (e.value ->> 'finished_good_id')::bigint)
    into v_supplied_count, v_distinct_count
  from pg_catalog.jsonb_array_elements(p_components) as e(value);

  if v_supplied_count <> v_distinct_count then
    raise exception 'Komponen duplikat tidak diperbolehkan.';
  end if;

  for v_recipe in
    select r.finished_good_id, r.qty_per_bundle, fg.unit
    from public.bundle_package_recipes r
    join public.finished_goods fg on fg.id = r.finished_good_id
    where r.package_id = p_package_id
    order by r.finished_good_id
    for share of r
  loop
    select count(*)
      into v_distinct_count
    from pg_catalog.jsonb_array_elements(p_components) as e(value)
    where (e.value ->> 'finished_good_id')::bigint = v_recipe.finished_good_id
      and coalesce(
        nullif(e.value ->> 'qty_used', '')::numeric,
        nullif(e.value ->> 'qty', '')::numeric,
        nullif(e.value ->> 'qty_per_bundle', '')::numeric
      ) = v_recipe.qty_per_bundle;

    if v_distinct_count <> 1 then
      raise exception 'Komponen yang dikirim tidak sama dengan resep paket.';
    end if;
  end loop;

  if not exists (
    select 1
    from public.bundle_package_recipes r
    where r.package_id = p_package_id
  ) then
    raise exception 'Paket belum memiliki resep.';
  end if;

  if v_supplied_count <> (
    select count(*)
    from public.bundle_package_recipes r
    where r.package_id = p_package_id
  ) then
    raise exception 'Komponen yang dikirim tidak sama dengan resep paket.';
  end if;

  v_packing_code :=
    'PCK-' ||
    pg_catalog.to_char(coalesce(p_date, current_date), 'YYYYMMDD') ||
    '-' ||
    pg_catalog.lpad(
      pg_catalog.nextval('public.bundle_package_packing_code_seq'::pg_catalog.regclass)::text,
      6,
      '0'
    );

  insert into public.bundle_package_packings (
    packing_code, package_id, location_id, packing_date,
    quantity, notes, created_by
  )
  values (
    v_packing_code, p_package_id, p_location_id, coalesce(p_date, current_date),
    p_quantity, p_notes, auth.uid()
  )
  returning id into v_packing_id;

  v_event_id := public.smpt_new_logistics_event(
    'BUNDLE_PACKING',
    'BUNDLE_PACKAGE_PACKINGS',
    v_packing_id,
    v_packing_code,
    coalesce(p_date, current_date),
    'Packing Paket Isian ' || v_package_name,
    null
  );

  for v_recipe in
    select r.finished_good_id, r.qty_per_bundle, fg.unit
    from public.bundle_package_recipes r
    join public.finished_goods fg on fg.id = r.finished_good_id
    where r.package_id = p_package_id
    order by r.finished_good_id
  loop
    insert into public.bundle_package_packing_items (
      packing_id, finished_good_id, qty_per_bundle, total_qty
    )
    values (
      v_packing_id,
      v_recipe.finished_good_id,
      v_recipe.qty_per_bundle,
      v_recipe.qty_per_bundle * p_quantity
    );

    perform public.smpt_apply_logistics_stock(
      v_event_id,
      'FINISHED_GOOD',
      v_recipe.finished_good_id,
      null,
      p_location_id,
      -(v_recipe.qty_per_bundle * p_quantity),
      v_recipe.unit,
      'BUNDLE PACKING OUT',
      'Komponen packing ' || v_packing_code
    );
  end loop;

  insert into public.bundle_package_balances (
    package_id, location_id, quantity, updated_at
  )
  values (p_package_id, p_location_id, p_quantity, pg_catalog.now())
  on conflict (package_id, location_id)
  do update set
    quantity = public.bundle_package_balances.quantity + excluded.quantity,
    updated_at = excluded.updated_at;

  return pg_catalog.jsonb_build_object(
    'success', true,
    'packing_id', v_packing_id,
    'packing_code', v_packing_code,
    'quantity', p_quantity
  );
end;
$$;

