create or replace function public.confirm_transfer_receipt(
  p_transfer_id bigint,
  p_received_qty numeric,
  p_reject_qty numeric default 0,
  p_damaged_qty numeric default 0,
  p_notes text default null,
  p_photo_url text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
  v_transfer public.finished_goods_transfers%rowtype;
  v_received numeric;
  v_reject numeric := coalesce(p_reject_qty, 0);
  v_damaged numeric := coalesce(p_damaged_qty, 0);
  v_delta numeric;
  v_unit text;
  v_event_id bigint;
begin
  if coalesce(auth.role(), '') <> 'service_role'
     and not coalesce(public.has_permission('mr_wu.confirm'), false) then
    raise exception 'Tidak memiliki izin mr_wu.confirm.'
      using errcode = '42501';
  end if;

  select * into v_transfer
  from public.finished_goods_transfers
  where id = p_transfer_id
  for update;
  if not found then
    raise exception 'Data transfer tidak ditemukan.';
  end if;
  if v_transfer.status = 'DIBATALKAN' then
    raise exception 'Transfer yang sudah dibatalkan tidak dapat dikonfirmasi.';
  end if;

  v_received := coalesce(p_received_qty, v_transfer.quantity);
  if v_received < 0 or v_reject < 0 or v_damaged < 0
     or v_received::text in ('NaN', 'Infinity', '-Infinity')
     or v_reject::text in ('NaN', 'Infinity', '-Infinity')
     or v_damaged::text in ('NaN', 'Infinity', '-Infinity')
     or v_received + v_reject + v_damaged <> v_transfer.quantity then
    raise exception 'Jumlah penerimaan, reject, dan rusak harus sama dengan jumlah yang dikirim.';
  end if;

  if p_photo_url is not null
     and p_photo_url !~ '/storage/v1/object/public/shipment-documents/surat-jalan/' then
    raise exception 'URL foto surat jalan tidak valid.';
  end if;

  v_delta := v_received - coalesce(v_transfer.received_qty, 0);
  if v_delta <> 0 then
    select unit into v_unit
    from public.finished_goods
    where id = v_transfer.finished_good_id;
    if not found or v_unit is null or btrim(v_unit) = '' then
      raise exception 'Barang jadi tidak ditemukan atau unit tidak valid.';
    end if;

    v_event_id := public.smpt_new_logistics_event(
      'TRANSFER_FG_RECEIPT', 'TRANSFER', v_transfer.id, v_transfer.transfer_code,
      pg_catalog.current_date, coalesce(p_notes, 'Penerimaan transfer barang jadi'), null
    );

    perform public.smpt_apply_logistics_stock(
      v_event_id, 'FINISHED_GOOD', v_transfer.finished_good_id, null,
      v_transfer.destination_location_id, v_delta, v_unit,
      case when v_transfer.received_qty is null then 'TRANSFER MASUK' else 'TRANSFER MASUK ADJUSTMENT' end,
      p_notes
    );
  end if;

  update public.finished_goods_transfers
  set delivery_status = 'DITERIMA',
      received_qty = v_received,
      reject_qty = v_reject,
      damaged_qty = v_damaged,
      received_at = pg_catalog.now(),
      received_by = auth.uid(),
      received_notes = p_notes,
      surat_jalan_photo_url = coalesce(p_photo_url, surat_jalan_photo_url)
  where id = p_transfer_id;

  return pg_catalog.jsonb_build_object('success', true, 'id', p_transfer_id);
end;
$$;

create or replace function public.transfer_finished_good(
  p_date date,
  p_finished_good_id bigint,
  p_source_location_id bigint,
  p_destination_location_id bigint,
  p_quantity numeric,
  p_notes text default null
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
  v_event_id bigint;
  v_transfer_id bigint;
  v_unit text;
  v_date date := coalesce(p_date, current_date);
begin
  if coalesce(auth.role(), '') <> 'service_role'
     and not coalesce(public.has_permission('transfer_barang_jadi.write'), false) then
    raise exception 'Tidak memiliki izin transfer_barang_jadi.write.'
      using errcode = '42501';
  end if;

  if p_finished_good_id is null or p_finished_good_id <= 0
     or p_source_location_id is null or p_source_location_id <= 0
     or p_destination_location_id is null or p_destination_location_id <= 0
     or p_source_location_id = p_destination_location_id
     or p_quantity is null or p_quantity <= 0
     or p_quantity::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Data transfer barang jadi tidak valid.';
  end if;

  select unit into v_unit
  from public.finished_goods
  where id = p_finished_good_id and status = 'AKTIF';
  if not found or v_unit is null or btrim(v_unit) = '' then
    raise exception 'Barang jadi aktif tidak ditemukan.';
  end if;

  perform 1 from public.locations where id = p_source_location_id and status = 'AKTIF';
  if not found then
    raise exception 'Lokasi asal aktif tidak ditemukan.';
  end if;
  perform 1 from public.locations where id = p_destination_location_id and status = 'AKTIF';
  if not found then
    raise exception 'Lokasi tujuan aktif tidak ditemukan.';
  end if;

  v_event_id := public.smpt_new_logistics_event(
    'TRANSFER_FG', 'TRANSFER', null, null, v_date, p_notes, null
  );
  perform public.smpt_apply_logistics_stock(
    v_event_id, 'FINISHED_GOOD', p_finished_good_id, null,
    p_source_location_id, -p_quantity, v_unit, 'TRANSFER KELUAR', p_notes
  );
  insert into public.finished_goods_transfers (
    transfer_date, finished_good_id, source_location_id, destination_location_id,
    quantity, notes, stock_event_id, delivery_status
  )
  values (
    v_date, p_finished_good_id, p_source_location_id, p_destination_location_id,
    p_quantity, p_notes, v_event_id, 'DIKIRIM'
  )
  returning id into v_transfer_id;

  return v_transfer_id;
end;
$$;

create function public.transfer_bundle_package(
  p_date date,
  p_package_id bigint,
  p_source_location_id bigint,
  p_destination_location_id bigint,
  p_quantity numeric,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
  v_source_quantity numeric;
  v_transfer_id bigint;
  v_transfer_code text;
  v_date date := coalesce(p_date, current_date);
begin
  if coalesce(auth.role(), '') <> 'service_role'
     and not coalesce(public.has_permission('transfer_barang_jadi.write'), false) then
    raise exception 'Tidak memiliki izin transfer_barang_jadi.write.'
      using errcode = '42501';
  end if;

  if p_package_id is null or p_package_id <= 0
     or p_source_location_id is null or p_source_location_id <= 0
     or p_destination_location_id is null or p_destination_location_id <= 0
     or p_source_location_id = p_destination_location_id
     or p_quantity is null or p_quantity <= 0
     or p_quantity::text in ('NaN', 'Infinity', '-Infinity') then
    raise exception 'Data transfer paket tidak valid.';
  end if;

  perform 1 from public.bundle_packages
  where id = p_package_id and status = 'AKTIF'
  for share;
  if not found then
    raise exception 'Paket aktif tidak ditemukan.';
  end if;

  select quantity into v_source_quantity
  from public.bundle_package_balances
  where package_id = p_package_id
    and location_id = p_source_location_id
  for update;

  if not found or v_source_quantity < p_quantity then
    raise exception 'Stok paket di lokasi asal tidak mencukupi.'
      using errcode = '23514';
  end if;

  v_transfer_code :=
    'TRP-' || pg_catalog.to_char(v_date, 'YYYYMMDD') || '-' ||
    pg_catalog.lpad(
      pg_catalog.nextval('public.bundle_package_transfer_code_seq'::pg_catalog.regclass)::text,
      6,
      '0'
    );

  insert into public.bundle_package_transfers (
    transfer_code, transfer_date, package_id, source_location_id,
    destination_location_id, quantity, notes, created_by
  )
  values (
    v_transfer_code, v_date, p_package_id, p_source_location_id,
    p_destination_location_id, p_quantity, p_notes, auth.uid()
  )
  returning id into v_transfer_id;

  update public.bundle_package_balances
  set quantity = quantity - p_quantity, updated_at = pg_catalog.now()
  where package_id = p_package_id and location_id = p_source_location_id;

  insert into public.bundle_package_transfer_movements (
    transfer_id, package_id, location_id, quantity_delta, movement_kind, created_by
  )
  values (
    v_transfer_id, p_package_id, p_source_location_id, -p_quantity,
    'TRANSFER_OUT', auth.uid()
  );

  return pg_catalog.jsonb_build_object(
    'success', true, 'transfer_id', v_transfer_id, 'transfer_code', v_transfer_code
  );
end;
$$;

create or replace function public.confirm_bundle_package_transfer(
  p_transfer_id bigint,
  p_received_qty numeric,
  p_reject_qty numeric default 0,
  p_damaged_qty numeric default 0,
  p_notes text default null,
  p_photo_url text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
  v_transfer public.bundle_package_transfers%rowtype;
  v_balance numeric;
  v_delta numeric;
  v_kind text;
begin
  if coalesce(auth.role(), '') <> 'service_role'
     and not coalesce(public.has_permission('mr_wu.confirm'), false) then
    raise exception 'Tidak memiliki izin mr_wu.confirm.'
      using errcode = '42501';
  end if;

  select * into v_transfer
  from public.bundle_package_transfers
  where id = p_transfer_id
  for update;

  if not found then
    raise exception 'Transfer paket tidak ditemukan.';
  end if;

  if p_received_qty is null or p_reject_qty is null or p_damaged_qty is null
     or p_received_qty < 0 or p_reject_qty < 0 or p_damaged_qty < 0
     or p_received_qty::text in ('NaN', 'Infinity', '-Infinity')
     or p_reject_qty::text in ('NaN', 'Infinity', '-Infinity')
     or p_damaged_qty::text in ('NaN', 'Infinity', '-Infinity')
     or p_received_qty + p_reject_qty + p_damaged_qty <> v_transfer.quantity then
    raise exception 'Jumlah diterima, reject, dan rusak harus sama dengan jumlah yang dikirim.';
  end if;

  if p_photo_url is not null
     and p_photo_url !~ '/storage/v1/object/public/shipment-documents/surat-jalan/' then
    raise exception 'URL foto surat jalan tidak valid.';
  end if;

  v_delta := p_received_qty - coalesce(v_transfer.received_qty, 0);
  if v_delta <> 0 then
    insert into public.bundle_package_balances (
      package_id, location_id, quantity, updated_at
    )
    values (
      v_transfer.package_id, v_transfer.destination_location_id, v_delta, pg_catalog.now()
    )
    on conflict (package_id, location_id)
    do update set
      quantity = public.bundle_package_balances.quantity + excluded.quantity,
      updated_at = excluded.updated_at
    returning quantity into v_balance;

    if v_balance < 0 then
      raise exception 'Penyesuaian penerimaan akan membuat saldo paket negatif.'
        using errcode = '23514';
    end if;

    v_kind := case
      when v_transfer.received_qty is null then 'TRANSFER_RECEIPT'
      else 'TRANSFER_RECEIPT_ADJUSTMENT'
    end;

    insert into public.bundle_package_transfer_movements (
      transfer_id, package_id, location_id, quantity_delta, movement_kind, created_by
    )
    values (
      v_transfer.id, v_transfer.package_id, v_transfer.destination_location_id,
      v_delta, v_kind, auth.uid()
    );
  end if;

  update public.bundle_package_transfers
  set status = 'DITERIMA',
      received_qty = p_received_qty,
      reject_qty = p_reject_qty,
      damaged_qty = p_damaged_qty,
      received_at = pg_catalog.now(),
      received_by = auth.uid(),
      received_notes = p_notes,
      surat_jalan_photo_url = coalesce(p_photo_url, surat_jalan_photo_url)
  where id = v_transfer.id;

  return pg_catalog.jsonb_build_object('success', true, 'id', v_transfer.id);
end;
$$;

